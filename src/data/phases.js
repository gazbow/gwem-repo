export function getPhaseForDay(addictionId, dayNumber) {
  const profile = ADDICTION_PROFILES[addictionId];
  if (!profile) return null;
  return profile.phases.find(p => dayNumber >= p.days[0] && dayNumber <= p.days[1]) || profile.phases[profile.phases.length - 1];
}

export function getDayNumber(startDate) {
  const start = new Date(startDate);
  start.setHours(0, 0, 0, 0);
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return Math.max(1, Math.floor((today - start) / 86400000) + 1);
}
